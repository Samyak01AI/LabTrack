CREATE TABLE IF NOT EXISTS assignments (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  course_code VARCHAR(32) NOT NULL,
  assignment_code VARCHAR(32) NOT NULL,
  title VARCHAR(160) NOT NULL,
  topic VARCHAR(80) NOT NULL,
  summary VARCHAR(240) NOT NULL,
  problem_statement TEXT NOT NULL,
  constraints_markdown TEXT NOT NULL,
  sample_cases JSON NOT NULL,
  due_at DATETIME(3) NOT NULL,
  max_score SMALLINT UNSIGNED NOT NULL DEFAULT 100,
  language_options JSON NOT NULL,
  status VARCHAR(12) NOT NULL DEFAULT 'draft',
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  CONSTRAINT assignments_created_by_fk FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE RESTRICT,
  CONSTRAINT assignments_course_nonblank CHECK (CHAR_LENGTH(TRIM(course_code)) > 0),
  CONSTRAINT assignments_code_nonblank CHECK (CHAR_LENGTH(TRIM(assignment_code)) > 0),
  CONSTRAINT assignments_title_nonblank CHECK (CHAR_LENGTH(TRIM(title)) > 0),
  CONSTRAINT assignments_topic_nonblank CHECK (CHAR_LENGTH(TRIM(topic)) > 0),
  CONSTRAINT assignments_summary_nonblank CHECK (CHAR_LENGTH(TRIM(summary)) > 0),
  CONSTRAINT assignments_statement_nonblank CHECK (CHAR_LENGTH(TRIM(problem_statement)) > 0),
  CONSTRAINT assignments_samples_array CHECK (JSON_TYPE(sample_cases) = 'ARRAY'),
  CONSTRAINT assignments_languages_array CHECK (JSON_TYPE(language_options) = 'ARRAY'),
  CONSTRAINT assignments_score_range CHECK (max_score BETWEEN 1 AND 1000),
  CONSTRAINT assignments_status_valid CHECK (status IN ('draft', 'published', 'archived')),
  UNIQUE KEY assignments_teacher_code_uq (created_by, assignment_code),
  KEY assignments_published_due_idx (status, due_at, title),
  KEY assignments_teacher_updated_idx (created_by, updated_at, title)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
