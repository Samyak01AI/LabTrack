CREATE TABLE IF NOT EXISTS grades (
  id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  submission_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  assignment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  student_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  teacher_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  correctness_score DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  logic_score DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  complexity_score DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  transparency_score DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  total_score DECIMAL(5,2) NOT NULL DEFAULT 0.00,
  max_score DECIMAL(5,2) NOT NULL DEFAULT 100.00,
  status VARCHAR(24) NOT NULL DEFAULT 'provisionally_scored',
  rubric_scores JSON DEFAULT NULL,
  feedback TEXT DEFAULT NULL,
  reopen_reason TEXT DEFAULT NULL,
  finalised_at DATETIME(3) DEFAULT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  CONSTRAINT grades_submission_fk FOREIGN KEY (submission_id) REFERENCES submissions(id) ON DELETE CASCADE,
  CONSTRAINT grades_assignment_fk FOREIGN KEY (assignment_id) REFERENCES assignments(id) ON DELETE CASCADE,
  CONSTRAINT grades_student_fk FOREIGN KEY (student_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT grades_teacher_fk FOREIGN KEY (teacher_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT grades_status_valid CHECK (status IN ('pending_review', 'provisionally_scored', 'finalised', 'reopened')),
  UNIQUE KEY uq_submission_grade (submission_id),
  KEY grades_assignment_idx (assignment_id, status),
  KEY grades_student_idx (student_id, status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

